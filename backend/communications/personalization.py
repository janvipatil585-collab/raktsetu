def generate_confirmation_message(registrant, drive, reporting_time="9:00 AM - 4:00 PM"):
    lang = registrant.preferred_language if registrant.preferred_language in CONFIRMATION_TEMPLATES else 'English'
    template = CONFIRMATION_TEMPLATES.get(lang, CONFIRMATION_TEMPLATES['English'])

    date_str = drive.date.strftime("%B %d, %Y") if hasattr(drive.date, 'strftime') else str(drive.date)

    return template.format(
        name=registrant.full_name,
        drive_name=drive.name,
        date=date_str,
        time=reporting_time,
        blood_group=registrant.blood_group
    )

def generate_message(registrant, drive, stage='reminder', reporting_time="9:00 AM - 4:00 PM"):
    if stage == 'confirmation':
        return generate_confirmation_message(registrant, drive, reporting_time)

    lang = registrant.preferred_language if registrant.preferred_language in REMINDER_TEMPLATES else 'English'
    template = REMINDER_TEMPLATES.get(lang, REMINDER_TEMPLATES['English'])

    date_str = drive.date.strftime("%B %d, %Y") if hasattr(drive.date, 'strftime') else str(drive.date)

    return template.format(
        name=registrant.full_name,
        date=date_str,
        time=reporting_time
    )
